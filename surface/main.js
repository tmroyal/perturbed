// Electron main process: owns the UDP socket (57130) and translates between OSC and the renderer,
// and runs the Claude drawer's terminal (a pty running Claude Code as the performance assistant).
const { app, BrowserWindow, ipcMain, dialog } = require('electron');
const dgram = require('node:dgram');
const path = require('node:path');
const pty = require('node-pty');

// ports can be moved (PERFORMED_PORT, PERFORMED_SURFACE_PORT) to run a second copy beside a performance
const SC = { host: '127.0.0.1', port: +(process.env.PERFORMED_PORT || 57120) };
const ICON = path.join(__dirname, 'icon', 'icon.png'); // generated by icon/make-icon.js
const LISTEN_PORT = +(process.env.PERFORMED_SURFACE_PORT || 57130);

const { encode, decode } = require('./osc');

// --- app ---
const sock = dgram.createSocket('udp4');
let win;
// The window can be gone while the pty or socket still produce output (quitting): drop it then.
const toRenderer = (channel, ...args) => {
  if (win && !win.isDestroyed()) win.webContents.send(channel, ...args);
};

function createWindow() {
  win = new BrowserWindow({
    width: 1100,
    height: 720,
    backgroundColor: '#2E3440',
    icon: ICON,
    webPreferences: { preload: path.join(__dirname, 'preload.js') },
  });
  win.loadFile('index.html');
  win.on('closed', () => {
    win = null;
    term?.kill();
  });
  // renderer errors go to the terminal too
  win.webContents.on('console-message', (e, ...old) => {
    const { level, message, sourceId, lineNumber } =
      e.message !== undefined ? e : { level: old[0], message: old[1], lineNumber: old[2], sourceId: old[3] };
    if (level === 'error' || level === 3) console.error(`[surface] ${message} (${sourceId}:${lineNumber})`);
  });
}

// Save/load dialogs; the brain reads and writes the file, the surface only picks the path.
const PERFORMANCES = path.join(__dirname, '..', 'performances');
const FILTERS = [{ name: 'Performance', extensions: ['json'] }];
ipcMain.handle('pick-file', async (_e, mode) => {
  const r =
    mode === 'save'
      ? await dialog.showSaveDialog(win, { defaultPath: path.join(PERFORMANCES, 'untitled.json'), filters: FILTERS })
      : await dialog.showOpenDialog(win, { defaultPath: PERFORMANCES, filters: FILTERS, properties: ['openFile'] });
  return r.canceled ? null : (r.filePath ?? r.filePaths[0]);
});

ipcMain.on('osc', (_e, addr, args) => sock.send(encode(addr, args), SC.port, SC.host));

// --- the Claude drawer: Claude Code in the repo, as the performance assistant (AGENTS.md, set by
// PERTURBED_AGENT=1), with agent-settings.json limiting its edits to performances/. When Claude
// exits, a shell stays open in the drawer. ---
const ROOT = path.join(__dirname, '..');
const AGENT_SETTINGS = path.join(__dirname, 'agent-settings.json');
let term = null;

ipcMain.on('term:start', (_e, cols, rows) => {
  if (term) return;
  const shell = process.env.SHELL || '/bin/zsh';
  // a fresh session even if Perturbed was started from inside another Claude Code session
  const env = { ...process.env, PERTURBED_AGENT: '1' };
  delete env.CLAUDECODE;
  delete env.CLAUDE_CODE_CHILD_SESSION;
  delete env.CLAUDE_CODE_ENTRYPOINT;
  term = pty.spawn(shell, ['-l', '-i', '-c', `claude --settings '${AGENT_SETTINGS}'; exec ${shell} -l -i`], {
    name: 'xterm-256color',
    cols,
    rows,
    cwd: ROOT,
    env,
  });
  term.onData((d) => toRenderer('term:data', d));
  term.onExit(() => {
    term = null;
    toRenderer('term:exit');
  });
});
ipcMain.on('term:input', (_e, d) => term?.write(d));
ipcMain.on('term:resize', (_e, cols, rows) => {
  try {
    term?.resize(cols, rows);
  } catch {}
});
app.on('before-quit', () => term?.kill());

sock.on('message', (msg) => {
  try {
    toRenderer('osc', decode(msg));
  } catch (e) {
    console.error('bad OSC', e);
  }
});
sock.bind(LISTEN_PORT);

app.setName('Perturbed');
app.whenReady().then(() => {
  app.dock?.setIcon(ICON); // macOS: otherwise the dock shows Electron's icon
  createWindow();
});
app.on('window-all-closed', () => app.quit());
